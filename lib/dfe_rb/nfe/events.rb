module DfeRb
  module Nfe
    # The detail (detEvento) of the events the RTC notes brought, checked against the schema of
    # the package PL_010h_v1.03. The package has no envEventoNFe schema of its own: the envelope
    # goes by event_1.00 (Distribution::Schemas), whose detEvento takes any content.
    #
    #   110300  Vinculação Pagamento (NT 2026.006): the issuer links a payment transaction to a
    #           note it has had authorized (Client#link_payment).
    #   110001  Cancelamento de Evento (NT 2025.002): the issuer takes one of its own events back
    #           (Client#cancel_event).
    #   412140  Tributação do Simples Nacional (NT 2026.005): generated by the Administração
    #           Tributária (tpAutor 5), never sent by the issuer, but read from the distribution.
    module Events
      PACKAGE = "Evento_PL_010h_v1.03"
      DETAILS = {"110001" => "e110001_v1.00.xsd", "110300" => "e110300_v1.00.xsd", "412140" => "e412140_v1.00.xsd"}.freeze

      module_function

      # Messages for what a <detEvento> (XML text, in the NF-e namespace) of event `type` breaks.
      def detail_issues(type, detail)
        file = DETAILS.fetch(type.to_s) { raise ArgumentError, "no detail schema for event #{type} (use #{DETAILS.keys.join(", ")})" }
        Xsd.issues(detail, package: PACKAGE, file: file)
      end
    end
  end
end
